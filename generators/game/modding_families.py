"""Universal-modder inspired families: the game-modding methodology.

The methodology (recon -> safe lab -> read the real code -> one slice ->
oracle -> package) comes from the public universal-modder project by
rehan_shei (Sep 2026). Everything here is executed on SYNTHETIC data
generated by this pipeline: no proprietary formats, no real game files,
no real installs.

Families:
  game_engine_recon   - fingerprint a synthetic install manifest (engine,
                        loader, anti-cheat, online) and pick a modding route.
  game_save_backup    - snapshot / diff / restore save folders with sha256
                        integrity gates (the `um backup` model).
  game_publish_lint   - lint a synthetic mod package for content that must
                        never ship (game files, leaked keys, decompiler
                        artifacts, absolute paths).
  game_oracle_replay  - trace-replay oracle: an f32-quantized toy sim is
                        replayed against a recorded trace and the first
                        divergence is reported.
"""
