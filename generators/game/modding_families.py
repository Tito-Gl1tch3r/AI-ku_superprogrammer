# ---------------------------------------------------------- shared helpers
def _f32(v: float) -> float:
    """Quantize to IEEE-754 single precision (game engines store f32)."""
    return struct.unpack("<f", struct.pack("<f", v))[0]


def _entry(rng: random.Random, path: str, head_hex: str,
           strings: list[str] | None = None) -> dict:
    """One manifest row of a synthetic install tree."""
    return {"path": path, "size": rng.randrange(4_000, 900_000_000),
            "head_hex": head_hex + "".join(rng.choice("0123456789ABCDEF")
                                           for _ in range(8)),
            "strings": strings or []}


def _decoys(rng: random.Random, game: str, count: int) -> list[dict]:
    """Harmless files that must not trip any detection rule."""
    pool = [f"{game}/logs/client.log", f"{game}/screenshots/clip.png",
            f"{game}/credits.odt", f"{game}/shaders/base.frag",
            f"{game}/localization/en.json", f"{game}/manual.pdf"]
    rng.shuffle(pool)
    out = []
    for p in pool[:count]:
        out.append(_entry(rng, p, ""))
    return out


