_REPLAY_TEMPLATE = '''import struct


def q32(v: float) -> float:
    """Quantize to IEEE-754 single precision (the engine stores f32)."""
    return struct.unpack("<f", struct.pack("<f", v))[0]


GRAVITY = q32(-0.2)
BOOST_MULT = q32(1.21)


def step(state: dict, action=None) -> dict:
    """One frame of the toy projectile sim.

    The engine polls input AFTER physics, so an action observed on frame
    t takes effect on frame t+1 (a one-shot boost multiplies vx once).
    """
    state = dict(state)
    pending = state.get("pending_boost", False)
    state["pending_boost"] = False
    if action == "boost":
        state["pending_boost"] = True
    vx = state["vx"]
    if pending:
        vx = q32(vx * BOOST_MULT)
    vy = q32(state["vy"] + GRAVITY)
    x = q32(state["x"] + vx)
    y = q32(state["y"] + vy)
    state.update(x=x, y=y, vx=vx, vy=vy)
    return state


def replay_compare(step_fn, actions, initial, expected, tol=1e-6) -> dict:
    """Trace-replay oracle: run actions through step_fn and compare each
    frame against the recorded trace. Variables are checked in the order
    x, y, vx, vy; the first one to exceed tol pins first_divergence.
    """
    state = dict(initial)
    per_var = {"x": 0.0, "y": 0.0, "vx": 0.0, "vy": 0.0}
    first_divergence = None
    for t, action in enumerate(actions):
        state = step_fn(state, action)
        exp = expected[t]
        for var in ("x", "y", "vx", "vy"):
            err = abs(state[var] - exp[var])
            if err > per_var[var]:
                per_var[var] = err
            if err > tol and first_divergence is None:
                first_divergence = {"frame": t, "var": var}
    verdict = "match" if first_divergence is None else "mismatch"
    return {"per_var_max_err": per_var,
            "first_divergence": first_divergence,
            "verdict": verdict}
'''


